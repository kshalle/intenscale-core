#include "riscv_test.h"
#include "test_macros.h"

# Size of the data chunk assigned for each thread.
#define ARR_SIZE 8192

# Number of concurrent threads (ROWs) used for the special test..
#define NUM_TEST_CONCURRENT 4

RVTEST_RV64UF
RVTEST_CODE_BEGIN

  la s0, tdat
  li s1, 32
  csrr a0, 0xb # Load mhartid.
  mul s1, s1, a0
  add s0, s0, s1
  TEST_CASE(2, a0, 0x40000000bf800000, fld f2, 0(s0); fsd f2, 16(s0); ld a0, 16(s0))
  TEST_CASE(3, a0, 0x40000000bf800000, fld f2, 0(s0); fsw f2, 16(s0); ld a0, 16(s0))
  TEST_CASE(4, a0, 0x40000000bf800000, flw f2, 0(s0); fsw f2, 16(s0); ld a0, 16(s0))
  TEST_CASE(5, a0, 0xc080000040400000, fld f2, 8(s0); fsd f2, 16(s0); ld a0, 16(s0))
  TEST_CASE(6, a0, 0xffffffff40400000, flw f2, 8(s0); fsd f2, 16(s0); ld a0, 16(s0))

  csrr a0, 0xb # Load mhartid.
  li s1, NUM_TEST_CONCURRENT
  blt s1, a0, cont
  li s5, 0

moreTesting:
  la s0, arrays
  li s2, ARR_SIZE
  li s3, ARR_SIZE/8
  mul s1, s2, a0
  add s0, s0, s1
  li s4, 0

repTest:
  add a1, a0, s4
  add a1, a1, s5
  add a2, a0, a1
  sw a1, 0(s0)
  sw a2, 4(s0)
  j repTestX

.space ARR_SIZE
repTestX:
  add s0, s0, 8
  add s4, s4, 1
  blt s4, s3, repTest

  la s0, arrays
  li s2, ARR_SIZE
  li s3, ARR_SIZE/8
  mul s1, s2, a0
  add s0, s0, s1
  li s4, 0

repCheck:
  add a1, a0, s4
  add a1, a1, s5
  add a2, a0, a1
  lw a3, 0(s0)
  lw a4, 4(s0)
  bne a1, a3, fail
  bne a2, a4, fail
  add s0, s0, 8
  add s4, s4, 1
  blt s4, s3, repCheck

  li a3, 0x1230
  add s5, s5, 0x123
  blt s5, a3, moreTesting
  
cont:
  TEST_PASSFAIL

RVTEST_CODE_END

